import { devices, expect, test } from '@playwright/test';
import { at, start, state } from './helpers';

test.use({ ...devices['iPhone 13'], browserName: 'webkit' });

test('mobile players can read all eight introductions and start the chapter', async ({ page }) => {
  await page.goto('/?fast');
  await page.getByRole('button', { name: 'New Game' }).tap();
  const roster = page.getByRole('dialog', { name: 'MEET THE PEOPLE OF KARIMKUNNU' });
  const begin = roster.getByRole('button', { name: 'Begin Story' });
  await expect(begin).toBeInViewport();
  await expect(roster.locator('.character-card')).toHaveCount(8);
  await roster.locator('.character-grid').evaluate(grid => { grid.scrollTop = grid.scrollHeight; });
  await expect(roster.getByRole('heading', { name: 'Sudhi', exact: true })).toBeInViewport();
  await expect(begin).toBeInViewport();
  await page.screenshot({ path: '.qa/story-introductions-mobile.png' });
  await begin.tap();
  await expect(page.getByRole('dialog', { name: 'Chapter 1 — Two Spies' })).toBeVisible();
  await page.getByRole('button', { name: 'Start Chapter' }).tap();
  await at(page, 'briefing');
});

test('touch movement, dialogue, pause, mute, and reload work in mobile WebKit', async ({ page }) => {
  const faults: string[] = [];
  page.on('pageerror', error => faults.push(error.message));
  page.on('console', message => { if (message.type() === 'error') faults.push(message.text()); });
  await start(page, '?fast');
  expect(await page.evaluate(() => Array.from(document.fonts).some(face => face.family.includes('Pixelta') && face.status === 'loaded'))).toBe(true);
  await expect(page.locator('.objective strong')).toHaveCSS('font-family', /Pixelta/);
  await at(page, 'briefing');
  const before = await state(page);
  const right = page.getByRole('button', { name: 'Move right' });
  await expect(right).toBeVisible();
  const rect = await right.boundingBox();
  if (!rect) throw new Error('Missing touch movement button');
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.down();
  await expect.poll(async () => (await state(page)).x).toBeGreaterThan(before.x + 10);
  await page.mouse.up();
  await page.getByRole('button', { name: 'Pause' }).tap();
  await expect(page.getByText('Paused', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Resume' }).tap();
  await page.getByRole('button', { name: 'Mute' }).tap();
  await expect(page.getByRole('button', { name: 'Unmute' })).toBeVisible();
  await page.evaluate(() => window.randuTest!.place('raghavan'));
  await page.getByRole('button', { name: 'Interact nearby' }).tap();
  await expect(page.locator('.dialogue')).toBeVisible();
  await expect(right).toBeHidden();
  await page.getByRole('button', { name: 'Advance dialogue' }).tap();
  await expect(page.locator('.dialogue p')).toContainText('Three raids.');
  await expect(page.locator('.dialogue p')).toHaveCSS('font-family', /Pixelta/);
  await page.screenshot({ path: '.qa/pixelta-mobile-dialogue.png' });
  await page.reload();
  await page.getByRole('button', { name: 'Continue' }).tap();
  await at(page, 'briefing');
  await expect(page.getByRole('button', { name: 'Unmute' })).toBeVisible();
  await page.getByRole('button', { name: 'Case File' }).tap();
  await expect(page.getByRole('heading', { name: 'Case File' })).toBeVisible();
  await page.getByRole('button', { name: 'Leads', exact: true }).tap();
  await expect(page.getByRole('heading', { name: 'Discovered Clues' })).toBeVisible();
  await expect(page.locator('.case-file h2')).toHaveCSS('font-family', /Pixelta/);
  await page.screenshot({ path: '.qa/pixelta-mobile-case.png' });
  await page.getByRole('button', { name: 'Close', exact: true }).tap();
  await expect(page.getByRole('button', { name: 'Move right' })).toBeVisible();
  expect(faults).toEqual([]);
});
