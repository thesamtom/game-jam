import { expect, test } from '@playwright/test';
import { at, beginGame, drain, go, start, state } from './helpers';

test('all nine chapters, checkpoint reload, scripted identity change, and credits', async ({ page }) => {
  test.setTimeout(45000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', event => { if (event.type() === 'error') errors.push(event.text()); });
  await page.addInitScript(() => document.addEventListener('click', event => {
    const button = event.target instanceof Element ? event.target.closest('.chapter-intro button') : null;
    const id = button?.closest<HTMLElement>('.chapter-intro')?.dataset.chapter;
    if (id) sessionStorage.setItem('chapters-seen', (sessionStorage.getItem('chapters-seen') ?? '') + id);
  }, true));
  await start(page, '?fast');
  await at(page, 'briefing');
  await talk('raghavan');
  await expect(page.locator('.dialogue')).toContainText('Kuttappan');
  await drain(page);
  await at(page, 'market');
  await go(page, 'marketEntry');
  await at(page, 'orders');
  await talk('shaji');
  await talk('package');
  await talk('shopkeeper');
  await talk('money');
  await talk('kuttappan');
  await at(page, 'tip');
  await talk('phone');
  await go(page, 'yardGate');
  await at(page, 'van');
  await go(page, 'van');
  await page.keyboard.press('e');
  await expect(page.locator('.dialogue')).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Continue' }).click();
  await at(page, 'van');
  expect((await state(page)).choices.pressure).toBe('quiet');
  expect((await state(page)).field.trust).toBeGreaterThan(30);
  expect((await state(page)).field.rank).toBe('Street Insider');
  await talk('van');
  await expect(page.locator('.dialogue')).toContainText('Vishnu');
  await drain(page);
  await at(page, 'tail');
  await go(page, 'huntLayby');
  await expect.poll(async () => (await state(page)).tailReady, { timeout: 10000 }).toBe(true);
  await go(page, 'handoff');
  await expect(page.locator('.dialogue')).toContainText('Kuttappan');
  await drain(page);
  await at(page, 'clue');
  await talk('handoff');
  await at(page, 'towerIn');
  await enter('roofDoor', 'meet');
  await talk('meeting');
  await at(page, 'injured');
  await talk('shajiInjured');
  await go(page, 'alleyExit');
  await at(page, 'raid');
  await talk('raidRendezvous');
  await expect(page.locator('.dialogue')).toContainText('Kuttappan');
  await drain(page);
  await at(page, 'survive');
  await go(page, 'raidExit');
  await at(page, 'evidence');
  await talk('evidence');
  await talk('clinic');
  await at(page, 'towerReturn');
  await enter('roofDoor', 'arrest');
  expect((await state(page)).identity).toBe('Alex');
  await talk('meeting');
  await expect(page.locator('.dialogue')).toContainText('Vishnu');
  await drain(page);
  await at(page, 'roofExit');
  expect((await state(page)).identity).toBe('Vishnu');
  await page.keyboard.press('j');
  await page.getByRole('button', { name: 'People', exact: true }).click();
  await expect(page.locator('.character-card').filter({ has: page.getByRole('heading', { name: 'Sudhi', exact: true }) }))
    .toContainText('He also worked for Kuttappan.');
  await page.reload();
  await page.getByRole('button', { name: 'Continue' }).click();
  await at(page, 'roofExit');
  expect((await state(page)).identity).toBe('Vishnu');
  await enter('exit', 'goodbye');
  expect((await state(page)).scene).toBe('Park');
  await talk('bench');
  await go(page, 'exit');
  await at(page, 'home');
  await talk('home');
  await expect(page.getByText('The End', { exact: true })).toBeVisible();
  await expect(page.getByText('Kenney · Tiny City · CC0')).toBeVisible();
  await page.getByRole('button', { name: 'Explore Karimkunnu' }).click();
  await at(page, 'free-roam');
  expect((await state(page)).identity).toBe('Vishnu');
  expect((await state(page)).field.achievements).toEqual(expect.arrayContaining(['assignment', 'trusted', 'witness', 'twospies']));
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Return to title' }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await expect(page.getByText('The End', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => sessionStorage.getItem('chapters-seen'))).toBe('123456789');
  expect(errors).toEqual([]);

  async function talk(mark: string) {
    await go(page, mark);
    await page.keyboard.press('e');
    await expect(page.locator('.dialogue')).toBeVisible();
    await drain(page);
  }
  async function enter(mark: string, objective: string) {
    await go(page, mark);
    await page.keyboard.press('e');
    await at(page, objective);
  }
});

test('corrupted save disables Continue and permits a fresh game', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('randu-chaaran:campaign', '{"version":1,"scene":"Roof"}'));
  await page.goto('/?fast');
  await expect(page.getByRole('button', { name: 'Continue' })).toBeDisabled();
  await beginGame(page);
  await at(page, 'briefing');
});
